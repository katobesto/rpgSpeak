/**
 * ComfyUI integration service.
 *
 * Flow:
 *  1. Load the pre-converted API-format workflow from  data/comfy-workflows/<name>_api.json
 *     (generated once by the UI→API converter script)
 *  2. Inject the character's imageDescription into the positive CLIPTextEncode node
 *  3. Queue the prompt via POST /prompt
 *  4. Poll GET /history/{prompt_id} until the image is ready
 *  5. Download and return the image as a Buffer
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

type WorkflowNode = {
  class_type: string;
  inputs: Record<string, unknown>;
  _meta?: Record<string, unknown>;
};

type Workflow = Record<string, WorkflowNode>;

type HistoryOutput = {
  images?: Array<{ filename: string; subfolder: string; type: string }>;
};

type HistoryEntry = {
  outputs: Record<string, HistoryOutput>;
  status: { completed: boolean; status_str: string };
};

export class ComfyUiService {
  constructor(
    private readonly baseUrl: string,
    private readonly cfClientId?: string | null,
    private readonly cfClientSecret?: string | null,
  ) {}

  /** Headers to add when Cloudflare Access protects the ComfyUI tunnel. */
  private get authHeaders(): Record<string, string> {
    if (this.cfClientId && this.cfClientSecret) {
      return {
        'CF-Access-Client-Id':     this.cfClientId,
        'CF-Access-Client-Secret': this.cfClientSecret,
      };
    }
    return {};
  }

  // ── Load pre-converted API-format workflow from local disk ───────────────
  // Files live at  data/comfy-workflows/<name>_api.json  (relative to project root).
  // They are generated by the Python converter script when a new workflow is added.
  loadWorkflow(name: string): Workflow {
    // __dirname equivalent in ESM
    const thisFile  = fileURLToPath(import.meta.url);
    const serverSrc = path.dirname(thisFile);                        // …/server/src/modules/characters
    const projectRoot = path.resolve(serverSrc, '../../../../');     // project root
    const filePath = path.join(projectRoot, 'data', 'comfy-workflows', `${name}_api.json`);

    if (!fs.existsSync(filePath)) {
      throw new Error(
        `Workflow "${name}" no encontrado en data/comfy-workflows/${name}_api.json. ` +
        'Asegúrate de haber ejecutado el script de conversión.',
      );
    }

    const raw = JSON.parse(fs.readFileSync(filePath, 'utf-8')) as Record<string, unknown>;
    return raw as Workflow;
  }

  // ── Load optional meta file (progressive workflows) ───────────────────────
  // Returns { previewNodeId, finalNodeId } if the workflow has a _meta.json sidecar.
  loadWorkflowMeta(name: string): { previewNodeId: string; finalNodeId: string } | null {
    const thisFile   = fileURLToPath(import.meta.url);
    const serverSrc  = path.dirname(thisFile);
    const projectRoot = path.resolve(serverSrc, '../../../../');
    const metaPath   = path.join(projectRoot, 'data', 'comfy-workflows', `${name}_meta.json`);
    if (!fs.existsSync(metaPath)) return null;
    try {
      return JSON.parse(fs.readFileSync(metaPath, 'utf-8')) as { previewNodeId: string; finalNodeId: string };
    } catch {
      return null;
    }
  }

  // ── Inject positive prompt text ───────────────────────────────────────────
  // Looks for the CLIPTextEncode node connected to the "positive" input of a
  // KSampler-family node and replaces its text.  Falls back to the first
  // CLIPTextEncode node if no sampler is found.
  injectPositivePrompt(workflow: Workflow, text: string): Workflow {
    const patched: Workflow = JSON.parse(JSON.stringify(workflow));

    const samplerClasses = [
      'KSampler',
      'KSamplerAdvanced',
      'SamplerCustom',
      'SamplerCustomAdvanced',
    ];

    let positiveNodeId: string | null = null;

    for (const node of Object.values(patched)) {
      if (samplerClasses.includes(node.class_type)) {
        const posInput = node.inputs?.positive;
        if (Array.isArray(posInput) && typeof posInput[0] === 'string') {
          positiveNodeId = posInput[0];
        }
        break;
      }
    }

    if (positiveNodeId && patched[positiveNodeId]) {
      patched[positiveNodeId].inputs.text = text;
      return patched;
    }

    // Fallback: patch the first CLIPTextEncode that has a "text" input
    for (const node of Object.values(patched)) {
      if (node.class_type === 'CLIPTextEncode' && 'text' in node.inputs) {
        node.inputs.text = text;
        break;
      }
    }

    return patched;
  }

  // ── Queue the prompt ──────────────────────────────────────────────────────
  // Returns both the promptId and the clientId used (needed for WS subscription).
  async queuePromptFull(workflow: Workflow, clientId: string): Promise<string> {
    const res = await fetch(`${this.baseUrl}/prompt`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', ...this.authHeaders },
      body: JSON.stringify({ prompt: workflow, client_id: clientId }),
    });
    if (!res.ok) {
      const body = await res.json().catch(() => null) as {
        error?: { type?: string; message?: string };
        node_errors?: Record<string, { errors?: Array<{ type?: string; details?: string }> }>;
      } | null;
      if (body?.error?.type === 'prompt_outputs_failed_validation' && body.node_errors) {
        const lines: string[] = [];
        for (const [, nodeErr] of Object.entries(body.node_errors)) {
          for (const e of nodeErr.errors ?? []) {
            if (e.type === 'value_not_in_list') {
              const match = e.details?.match(/^(\w+):\s*'([^']+)'\s+not in \[/);
              if (match) {
                const [, field, value] = match;
                lines.push(`Modelo no encontrado — ${field}: "${value}". Descárgalo y colócalo en la carpeta correspondiente de ComfyUI.`);
              } else {
                lines.push(e.details ?? e.type ?? 'error desconocido');
              }
            } else {
              lines.push(e.details ?? e.type ?? 'error desconocido');
            }
          }
        }
        throw new Error(`ComfyUI: workflow inválido — ${lines.join(' | ')}`);
      }
      const text = body ? JSON.stringify(body) : res.statusText;
      throw new Error(`ComfyUI: error al encolar prompt (${res.status}): ${text}`);
    }
    const data = (await res.json()) as { prompt_id?: string; error?: unknown };
    if (!data.prompt_id) {
      if (data.error) throw new Error(`ComfyUI: el workflow tiene errores — ${JSON.stringify(data.error).slice(0, 200)}`);
      throw new Error('ComfyUI: la respuesta no incluye prompt_id');
    }
    return data.prompt_id;
  }

  async queuePrompt(workflow: Workflow): Promise<string> {
    const clientId = `rpgspeak-${Date.now()}`;
    const res = await fetch(`${this.baseUrl}/prompt`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', ...this.authHeaders },
      body: JSON.stringify({ prompt: workflow, client_id: clientId }),
    });

    if (!res.ok) {
      const body = await res.json().catch(() => null) as {
        error?: { type?: string; message?: string };
        node_errors?: Record<string, { errors?: Array<{ type?: string; details?: string }> }>;
      } | null;

      // Validation errors: parse node_errors for a human-readable message
      if (body?.error?.type === 'prompt_outputs_failed_validation' && body.node_errors) {
        const lines: string[] = [];
        for (const [, nodeErr] of Object.entries(body.node_errors)) {
          for (const e of nodeErr.errors ?? []) {
            if (e.type === 'value_not_in_list') {
              // e.g. "ckpt_name: 'foo.safetensors' not in []"
              const match = e.details?.match(/^(\w+):\s*'([^']+)'\s+not in \[/);
              if (match) {
                const [, field, value] = match;
                lines.push(`Modelo no encontrado — ${field}: "${value}". Descárgalo y colócalo en la carpeta correspondiente de ComfyUI.`);
              } else {
                lines.push(e.details ?? e.type ?? 'error desconocido');
              }
            } else {
              lines.push(e.details ?? e.type ?? 'error desconocido');
            }
          }
        }
        throw new Error(`ComfyUI: workflow inválido — ${lines.join(' | ')}`);
      }

      const text = body ? JSON.stringify(body) : res.statusText;
      throw new Error(`ComfyUI: error al encolar prompt (${res.status}): ${text}`);
    }

    const data = (await res.json()) as { prompt_id?: string; error?: unknown };
    if (!data.prompt_id) {
      // ComfyUI sometimes returns 200 with an error body (e.g. validation failed)
      if (data.error) {
        throw new Error(`ComfyUI: el workflow tiene errores — ${JSON.stringify(data.error).slice(0, 200)}`);
      }
      throw new Error('ComfyUI: la respuesta no incluye prompt_id');
    }
    return data.prompt_id;
  }

  // ── Poll until the image is ready ─────────────────────────────────────────
  async waitForResult(promptId: string, timeoutMs = 600_000): Promise<HistoryEntry> {
    const deadline = Date.now() + timeoutMs;
    const POLL_INTERVAL = 1_500;

    while (Date.now() < deadline) {
      await sleep(POLL_INTERVAL);

      const res = await fetch(`${this.baseUrl}/history/${promptId}`, {
        headers: { ...this.authHeaders },
      });
      if (!res.ok) continue;

      const history = (await res.json()) as Record<string, HistoryEntry>;
      const entry = history[promptId];

      if (entry) {
        if (entry.status?.status_str === 'error') {
          throw new Error('ComfyUI: la generación terminó con error');
        }
        if (entry.status?.completed !== false) {
          return entry;
        }
      }
    }

    throw new Error('ComfyUI: timeout esperando resultado (>10 min)');
  }

  // ── Download image ────────────────────────────────────────────────────────
  async downloadImage(filename: string, subfolder = '', type = 'output'): Promise<Buffer> {
    const qs = new URLSearchParams({ filename, subfolder, type }).toString();
    const res = await fetch(`${this.baseUrl}/view?${qs}`, {
      headers: { ...this.authHeaders },
    });
    if (!res.ok) {
      throw new Error(`ComfyUI: error descargando "${filename}" (${res.status})`);
    }
    return Buffer.from(await res.arrayBuffer());
  }

  // ── Upload a local image file to ComfyUI's input folder ──────────────────
  // Returns the filename as ComfyUI knows it (used in LoadImage nodes).
  async uploadImage(localPath: string): Promise<string> {
    const buffer = fs.readFileSync(localPath);
    const ext = path.extname(localPath) || '.png';
    const name = `rpgspeak_ref_${Date.now()}${ext}`;

    // ComfyUI upload/image expects multipart/form-data
    const boundary = `----FormBoundary${Date.now()}`;
    const body = Buffer.concat([
      Buffer.from(
        `--${boundary}\r\nContent-Disposition: form-data; name="image"; filename="${name}"\r\nContent-Type: image/png\r\n\r\n`,
      ),
      buffer,
      Buffer.from(`\r\n--${boundary}\r\nContent-Disposition: form-data; name="type"\r\n\r\ninput\r\n`),
      Buffer.from(`--${boundary}\r\nContent-Disposition: form-data; name="overwrite"\r\n\r\ntrue\r\n`),
      Buffer.from(`--${boundary}--\r\n`),
    ]);

    const res = await fetch(`${this.baseUrl}/upload/image`, {
      method: 'POST',
      headers: { 'Content-Type': `multipart/form-data; boundary=${boundary}`, ...this.authHeaders },
      body,
    });

    if (!res.ok) {
      throw new Error(`ComfyUI: error subiendo imagen de referencia (${res.status})`);
    }

    const data = (await res.json()) as { name: string };
    return data.name;
  }

  // ── Inject FluxResolutionNode overrides (megapixel + aspect_ratio) ─────────
  // Finds the first FluxResolutionNode and patches its inputs.
  // Values must match the node's combo-box enums exactly (e.g. "2.0", "5:7 (Balanced Portrait)").
  injectResolution(workflow: Workflow, megapixel?: string, aspectRatio?: string): Workflow {
    if (!megapixel && !aspectRatio) return workflow;
    const patched: Workflow = JSON.parse(JSON.stringify(workflow));
    for (const node of Object.values(patched)) {
      if (node.class_type === 'FluxResolutionNode') {
        if (megapixel)   node.inputs.megapixel    = megapixel;
        if (aspectRatio) node.inputs.aspect_ratio = aspectRatio;
        break;
      }
    }
    return patched;
  }

  // ── Inject a reference image filename into the LoadImage node ─────────────
  injectReferenceImage(workflow: Workflow, comfyFilename: string): Workflow {
    const patched: Workflow = JSON.parse(JSON.stringify(workflow));
    for (const node of Object.values(patched)) {
      if (node.class_type === 'LoadImage') {
        node.inputs.image = comfyFilename;
        break;
      }
    }
    return patched;
  }

  // ── Full pipeline (standard — no reference image) ─────────────────────────
  async generateImage(
    workflowName: string,
    positivePrompt: string,
    overrides?: { megapixel?: string; aspectRatio?: string },
  ): Promise<{ buffer: Buffer; filename: string }> {
    const workflow = this.loadWorkflow(workflowName);
    let patched = this.injectPositivePrompt(workflow, positivePrompt);
    if (overrides?.megapixel || overrides?.aspectRatio) {
      patched = this.injectResolution(patched, overrides.megapixel, overrides.aspectRatio);
    }
    return this.runWorkflow(patched);
  }

  // ── Full pipeline (BETA — with character reference image) ─────────────────
  async generateImageWithReference(
    workflowName: string,
    positivePrompt: string,
    referenceImagePath: string,
  ): Promise<{ buffer: Buffer; filename: string }> {
    // 1. Upload reference image to ComfyUI
    const comfyFilename = await this.uploadImage(referenceImagePath);

    // 2. Load workflow, inject prompt + reference
    const workflow = this.loadWorkflow(workflowName);
    let patched = this.injectPositivePrompt(workflow, positivePrompt);
    patched = this.injectReferenceImage(patched, comfyFilename);

    // 3. Randomise seed so each run is different
    for (const node of Object.values(patched)) {
      if (node.class_type === 'KSampler' || node.class_type === 'KSamplerAdvanced') {
        node.inputs.seed = Math.floor(Math.random() * 2 ** 32);
        break;
      }
    }

    return this.runWorkflow(patched);
  }

  // ── Shared: queue → wait → download ──────────────────────────────────────
  private async runWorkflow(workflow: Workflow): Promise<{ buffer: Buffer; filename: string }> {
    const promptId = await this.queuePrompt(workflow);
    const result = await this.waitForResult(promptId);

    let imageInfo: { filename: string; subfolder: string; type: string } | null = null;
    for (const output of Object.values(result.outputs)) {
      if (output.images && output.images.length > 0) {
        imageInfo = output.images[0];
        break;
      }
    }

    if (!imageInfo) {
      throw new Error('ComfyUI: el resultado no contiene imágenes');
    }

    const buffer = await this.downloadImage(imageInfo.filename, imageInfo.subfolder, imageInfo.type);
    return { buffer, filename: imageInfo.filename };
  }

  // ── Wait until a specific node has produced output ────────────────────────
  // Used for progressive workflows where an early node saves a preview image
  // before the full pipeline (upscale, face detailer…) completes.
  async waitForNodeOutput(
    promptId: string,
    nodeId: string,
    timeoutMs = 600_000,
  ): Promise<{ buffer: Buffer; filename: string }> {
    const deadline = Date.now() + timeoutMs;
    const POLL_INTERVAL = 1_500;

    while (Date.now() < deadline) {
      await sleep(POLL_INTERVAL);

      const res = await fetch(`${this.baseUrl}/history/${promptId}`, {
        headers: { ...this.authHeaders },
      });
      if (!res.ok) continue;

      const history = (await res.json()) as Record<string, HistoryEntry>;
      const entry = history[promptId];
      if (!entry) continue;

      if (entry.status?.status_str === 'error') {
        throw new Error('ComfyUI: la generación terminó con error');
      }

      // Check if this specific node already has output (even if workflow is still running)
      const nodeOutput = entry.outputs[nodeId];
      if (nodeOutput?.images && nodeOutput.images.length > 0) {
        const imageInfo = nodeOutput.images[0];
        const buffer = await this.downloadImage(imageInfo.filename, imageInfo.subfolder, imageInfo.type);
        return { buffer, filename: imageInfo.filename };
      }
    }

    throw new Error(`ComfyUI: timeout esperando salida del nodo ${nodeId}`);
  }

  // ── Progressive generation ─────────────────────────────────────────────────
  startProgressiveGeneration(
    workflowName: string,
    positivePrompt: string,
    previewNodeId: string,
    finalNodeId: string,
    overrides?: { megapixel?: string; aspectRatio?: string },
  ): {
    waitForPreview: () => Promise<{ buffer: Buffer; filename: string }>;
    waitForFinal:   () => Promise<{ buffer: Buffer; filename: string }>;
  } {
    const workflow = this.loadWorkflow(workflowName);
    let patched    = this.injectPositivePrompt(workflow, positivePrompt);
    if (overrides?.megapixel || overrides?.aspectRatio) {
      patched = this.injectResolution(patched, overrides.megapixel, overrides.aspectRatio);
    }
    const promptIdPromise = this.queuePrompt(patched);
    return {
      waitForPreview: async () => {
        const promptId = await promptIdPromise;
        return this.waitForNodeOutput(promptId, previewNodeId);
      },
      waitForFinal: async () => {
        const promptId = await promptIdPromise;
        return this.waitForNodeOutput(promptId, finalNodeId);
      },
    };
  }

  // ── Progressive generation with real-time WebSocket progress ──────────────
  // Uses ComfyUI's WS endpoint to relay step-level progress (step N/M).
  // onProgress is called with every progress event from ComfyUI.
  async startProgressiveWithProgress(
    workflowName: string,
    positivePrompt: string,
    previewNodeId: string,
    finalNodeId: string,
    onProgress: (event: ComfyProgressEvent) => void,
    overrides?: { megapixel?: string; aspectRatio?: string },
  ): Promise<{
    waitForPreview: () => Promise<{ buffer: Buffer; filename: string }>;
    waitForFinal:   () => Promise<{ buffer: Buffer; filename: string }>;
    disconnect:     () => void;
  }> {
    const clientId = `rpgspeak-${Date.now()}`;
    const workflow = this.loadWorkflow(workflowName);
    let patched    = this.injectPositivePrompt(workflow, positivePrompt);
    if (overrides?.megapixel || overrides?.aspectRatio) {
      patched = this.injectResolution(patched, overrides.megapixel, overrides.aspectRatio);
    }

    // Build nodeId → human-readable label map from this workflow
    const nodeNameMap = new Map<string, string>(
      Object.entries(patched).map(([id, node]) => [
        id,
        NODE_LABELS[node.class_type] ?? node.class_type,
      ])
    );

    // Subscribe to WS BEFORE queuing so we don't miss early events
    const wsUrl = this.baseUrl.replace(/^http/, 'ws') + `/ws?clientId=${clientId}`;
    let ws: import('node:stream').Duplex | null = null;
    let wsDisconnected = false;

    const disconnect = () => {
      wsDisconnected = true;
      try { (ws as any)?.close?.(); } catch { /* ignore */ }
    };

    // Subscribe asynchronously — don't block queuing
    this.subscribeComfyWs(wsUrl, clientId, nodeNameMap, onProgress, () => wsDisconnected)
      .then((socket) => { ws = socket as any; })
      .catch(() => { /* WS is optional — generation continues without it */ });

    const promptIdPromise = this.queuePromptFull(patched, clientId);

    return {
      waitForPreview: async () => {
        const promptId = await promptIdPromise;
        return this.waitForNodeOutput(promptId, previewNodeId);
      },
      waitForFinal: async () => {
        const promptId = await promptIdPromise;
        const result = await this.waitForNodeOutput(promptId, finalNodeId);
        disconnect(); // done — close WS
        return result;
      },
      disconnect,
    };
  }

  // ── Subscribe to ComfyUI WebSocket for real-time progress ─────────────────
  private async subscribeComfyWs(
    wsUrl: string,
    _clientId: string,
    nodeNameMap: Map<string, string>,
    onProgress: (event: ComfyProgressEvent) => void,
    isCancelled: () => boolean,
  ): Promise<unknown> {
    const WSClass = (globalThis as any).WebSocket as typeof WebSocket | undefined;
    if (!WSClass) return null;

    return new Promise((resolve) => {
      const socket = new WSClass(wsUrl);

      socket.addEventListener('open', () => resolve(socket));
      socket.addEventListener('error', () => resolve(null));

      socket.addEventListener('message', (evt: MessageEvent) => {
        if (isCancelled()) { socket.close(); return; }
        try {
          const msg = JSON.parse(evt.data as string) as {
            type: string;
            data?: { value?: number; max?: number; node?: string | null; prompt_id?: string };
          };
          if (msg.type === 'progress' && msg.data) {
            onProgress({ type: 'progress', value: msg.data.value ?? 0, max: msg.data.max ?? 1 });
          } else if (msg.type === 'executing' && msg.data?.node) {
            const nodeId   = msg.data.node;
            const nodeName = nodeNameMap.get(nodeId) ?? nodeId;
            onProgress({ type: 'node', nodeId, nodeName });
          }
        } catch { /* ignore malformed */ }
      });
    });
  }
}

export interface ComfyProgressEvent {
  type: 'progress' | 'node';
  value?: number;     // for 'progress': current step
  max?: number;       // for 'progress': total steps
  nodeId?: string;    // for 'node': which node started executing
  nodeName?: string;  // for 'node': human-readable name of the node
}

// ── Map ComfyUI class_type → human-readable Spanish label ─────────────────
const NODE_LABELS: Record<string, string> = {
  KSampler:              'Generando imagen base',
  KSamplerAdvanced:      'Generando imagen base',
  SeedVR2VideoUpscaler:  'Escalando a 4K',
  FaceDetailer:          'Mejorando rostros',
  VAEDecode:             'Decodificando imagen',
  VAEEncode:             'Codificando imagen',
  SeedVR2LoadDiTModel:   'Cargando modelo 4K',
  SeedVR2LoadVAEModel:   'Cargando VAE 4K',
  SAMLoader:             'Cargando detector',
  UltralyticsDetectorProvider: 'Preparando detector',
  SaveImage:             'Guardando imagen',
  CLIPTextEncode:        'Codificando prompt',
  ImageScaleBy:          'Escalando imagen',
  ColorCorrect:          'Corrigiendo colores',
};

function sleep(ms: number) {
  return new Promise<void>((r) => setTimeout(r, ms));
}
